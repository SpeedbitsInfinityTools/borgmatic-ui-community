const os = require('os');
const path = require('path');
const fs = require('fs-extra');

const { migrateLockWait, migrateLockWaitText } = require('../lock-wait-migration');

const HEADER = '# Generated by Borgmatic-UI\n# Backup ID: abc\n\n';

describe('migrateLockWaitText', () => {
    test('raises the legacy 60s value', () => {
        const text = `${HEADER}source_directories:\n  - /data\nlock_wait: 60\nkeep_daily: 7\n`;
        expect(migrateLockWaitText(text)).toBe(
            `${HEADER}source_directories:\n  - /data\nlock_wait: 600\nkeep_daily: 7\n`
        );
    });

    test('adds lock_wait when missing', () => {
        const text = `${HEADER}source_directories:\n  - /data\n`;
        expect(migrateLockWaitText(text)).toBe(`${HEADER}source_directories:\n  - /data\nlock_wait: 600\n`);
    });

    test('appends after a trailing block scalar without altering it', () => {
        const text = `${HEADER}commands:\n  - before: action\n    run:\n      - |\n        echo hi\n        echo there\n`;
        const out = migrateLockWaitText(text);
        expect(out).toBe(`${text}lock_wait: 600\n`);
    });

    test('keeps a customised value', () => {
        expect(migrateLockWaitText(`${HEADER}lock_wait: 300\n`)).toBeNull();
    });

    test('is a no-op once applied', () => {
        expect(migrateLockWaitText(`${HEADER}lock_wait: 600\n`)).toBeNull();
    });

    test('ignores configs not generated by Borgmatic-UI', () => {
        expect(migrateLockWaitText('source_directories:\n  - /data\nlock_wait: 60\n')).toBeNull();
    });

    test('does not touch a nested lock_wait', () => {
        const text = `${HEADER}lock_wait: 120\nother:\n  lock_wait: 60\n`;
        expect(migrateLockWaitText(text)).toBeNull();
    });
});

describe('migrateLockWait', () => {
    let dir;

    beforeEach(async () => {
        dir = await fs.mkdtemp(path.join(os.tmpdir(), 'lockwait-'));
    });

    afterEach(async () => {
        await fs.remove(dir);
    });

    test('rewrites only the files that need it', async () => {
        await fs.writeFile(path.join(dir, 'a.yaml'), `${HEADER}lock_wait: 60\n`);
        await fs.writeFile(path.join(dir, 'b.yaml'), `${HEADER}lock_wait: 600\n`);
        await fs.writeFile(path.join(dir, 'notes.txt'), 'lock_wait: 60\n');

        const result = await migrateLockWait({ backupsDir: dir });

        expect(result).toEqual({ filesChanged: 1, errors: [] });
        expect(await fs.readFile(path.join(dir, 'a.yaml'), 'utf8')).toBe(`${HEADER}lock_wait: 600\n`);
        expect(await fs.readFile(path.join(dir, 'notes.txt'), 'utf8')).toBe('lock_wait: 60\n');
    });

    test('returns empty result when the directory is missing', async () => {
        const result = await migrateLockWait({ backupsDir: path.join(dir, 'nope') });
        expect(result).toEqual({ filesChanged: 0, errors: [] });
    });
});
